/** Para escribir fechas en el idioma elegido. */
export const LOCALE: Record<Idioma, string> = { es: 'es-ES', en: 'en-GB', fr: 'fr-FR', tr: 'tr-TR' };

const DICCIONARIOS: Record<Idioma, Diccionario> = { es, en, fr, tr };

export function traducir(idioma: Idioma, clave: Clave, valores: Record<string, string | number> = {}): string {
  return DICCIONARIOS[idioma][clave].replace(/\{(\w+)\}/g, (_, k) => String(valores[k] ?? ''));
}

export type Tr = (clave: Clave, valores?: Record<string, string | number>) => string;

export interface ContextoIdioma {
  idioma: Idioma;
  cambiar: (idioma: Idioma) => void;
  t: Tr;
}

export const IdiomaContexto = createContext<ContextoIdioma>({
  idioma: 'es',
  cambiar: () => undefined,
  t: (clave, valores) => traducir('es', clave, valores),
});

export const useIdioma = () => useContext(IdiomaContexto);
