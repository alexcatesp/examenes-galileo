export const IDIOMAS = ['es', 'en', 'fr', 'tr'] as const;
export type Idioma = (typeof IDIOMAS)[number];

/** Cada idioma se nombra en sí mismo: quien no lee español tiene que poder reconocerlo. */
export const NOMBRE_IDIOMA: Record<Idioma, string> = { es: 'Español', en: 'English', fr: 'Français', tr: 'Türkçe' };
/** Nombre en español, para el .md que lee el profesor. */
export const NOMBRE_IDIOMA_ES: Record<Idioma, string> = { es: 'español', en: 'inglés', fr: 'francés', tr: 'turco' };

const CLAVE = 'galileo-idioma';

export function idiomaInicial(): Idioma {
  try {
    const guardado = localStorage.getItem(CLAVE);
    if (guardado && (IDIOMAS as readonly string[]).includes(guardado)) return guardado as Idioma;
  } catch { /* sin almacenamiento: se usa el idioma del navegador */ }
  const nav = (navigator.language || 'es').slice(0, 2).toLowerCase();
  return (IDIOMAS as readonly string[]).includes(nav) ? (nav as Idioma) : 'es';
}

export function recordarIdioma(idioma: Idioma): void {
  try { localStorage.setItem(CLAVE, idioma); } catch { /* nada */ }
}

